# Builds one standalone CUDA runner script for each benchmark entry.
#   STADE_SRC=/path/to/src/STADE.jl julia make_scripts.jl OUTDIR SPEC
# SPEC: entries "kernel:cuda:fuse:size1+size2", separated by spaces. A size that ends with "!" is checked against the CPU.
# Example: "heat3d_step:cuda:1:tiny!+small!+bench_1e5"
# Environment:
#   STADE_PO=0       generate the adjoint with primal_outputs = false
#   STADE_FRESHKW=1  generate the adjoint with fresh_gradient = true
#   STADE_RUNNER     path of the runner body, default gpu/runner_body.jl of this folder
haskey(ENV, "STADE_SRC") || error("set STADE_SRC to the path of STADE.jl/src/STADE.jl")
const PKG = normpath(joinpath(@__DIR__, ".."))
include(joinpath(PKG, "tools", "check_kernel.jl"))   # STADE, ck_roles, inputs

function gen_files(k, fuse, gendir)
    f = bench_kernel_path(k)
    b = joinpath(gendir, "$(k).f$(Int(fuse)).b.jl")
    STADE.stade_adjoint_file(f, b; keep_push_pop = false, fuse_ii_loops = fuse, primal_outputs = get(ENV, "STADE_PO", "1") == "1")
    c = joinpath(gendir, "$(k).f$(Int(fuse)).b.cuda.jl")
    kg = haskey(ENV, "STADE_FRESHKW") ? (fresh_gradient = ENV["STADE_FRESHKW"] == "1",) : NamedTuple()
    STADE.stade_cuda_file(b, c; kg...)
    return b, c
end

# remove the package-manager lines of the generated file, the cluster default environment already has the packages
function strip_pkg(txt)
    keep = String[]
    for l in split(txt, "\n")
        occursin(r"^import Pkg\s*$", l) && continue
        occursin(r"^haskey\(Pkg", l) && continue
        push!(keep, l)
    end
    return join(keep, "\n")
end

function build(k, backend, fuse, sizes, outdir, gendir)
    backend == "cuda" || error("only the cuda backend is supported, got $backend")
    b, c = gen_files(k, fuse, gendir)
    deps, indeps = ck_roles(bench_kernel_path(k))
    gpu = strip_pkg(read(c, String))
    cpu = read(b, String)
    inputs = read(joinpath(PKG, "tools", "inputs.jl"), String)
    runner = read(get(ENV, "STADE_RUNNER", joinpath(PKG, "gpu", "runner_body.jl")), String)
    sizes_lit = "[" * join(("(\"$(rstrip(s, '!'))\", $(endswith(s, "!")))" for s in sizes), ", ") * "]"
    hdr = """
    # Generated by make_scripts.jl: $(k), backend $(backend), fuse_ii_loops = $(fuse)
    const NAME = "$k"
    const BACKEND = :$(backend)
    const FUSE = $(fuse)
    const PROFILE = $(get(ENV, "STADE_PROFILE", "false"))
    const DEPS = Symbol[$(join((":" * string(d) for d in sort(collect(deps))), ", "))]
    const SIZES = $sizes_lit
    """
    path = joinpath(outdir, "$(k).$(backend).f$(Int(fuse)).jl")
    write(path, hdr * "\n" * gpu * "\n\n# ---- CPU primal and adjoint (keep_push_pop = false) ----\n" * cpu * "\n\n# ---- inputs ----\n" * inputs * "\n" * runner)
    return path
end

if abspath(PROGRAM_FILE) == @__FILE__
    outdir = ARGS[1]; spec = ARGS[2]
    mkpath(outdir); gendir = joinpath(outdir, "gen"); mkpath(gendir)
    for ent in split(spec)
        k, be, fu, sz = split(ent, ":")
        println(build(k, be, fu == "1", split(sz, "+"), outdir, gendir))
    end
end
